-- 0004_inbox_kind.sql — тип записи inbox.
--
-- 'raw'  — сырьё для /draft: заметка, материал, идея. Поведение по умолчанию,
--          поэтому существующие записи получают именно его.
-- 'post' — готовый текст (например, от «Скилла статей»). Черновик по нему
--          писать не надо, его публикуют как есть.
--
-- ВНИМАНИЕ про имя. Колонка kind уже была в 0001 с ДРУГИМ смыслом
-- ('text'|'photo'|'video'|'document') и удалена в 0003 вместе с медиа.
-- Здесь заводится заново и с нуля: со старой семантикой ничего общего.

ALTER TABLE inbox ADD COLUMN kind TEXT NOT NULL DEFAULT 'raw';
